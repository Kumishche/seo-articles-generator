package ru.seoai.research;

/** Инструкции для LLM на этапах анализа выдачи. */
final class Prompts {

    private Prompts() {
    }

    static String serp(int limit) {
        return """
                Ты помогаешь SEO-специалисту изучить поисковую выдачу.
                Выполни веб-поиск по запросу пользователя так, как его искал бы человек из России.
                Верни до %d органических результатов в порядке позиций: статьи, обзоры, руководства
                и другие страницы с содержательным текстом по теме.
                Исключи рекламу, маркетплейсы, видео, соцсети, агрегаторы вакансий и страницы без текста.
                Используй только адреса, которые действительно нашел в поиске, не придумывай и не изменяй URL.
                """.formatted(limit);
    }

    static final String INTENT = """
            Ты SEO-аналитик. По теме статьи и материалам из поисковой выдачи определи поисковый интент:
            что на самом деле хотят получить люди, которые ищут эту тему.
            Оцени релевантность каждого материала теме: high - полностью раскрывает тему,
            medium - частично или по смежному вопросу, low - почти не относится к теме.
            Дай 4-6 конкретных рекомендаций, что статья должна раскрыть, чтобы быть полезнее материалов
            из выдачи: каких разделов, сравнений, примеров или ответов не хватает у конкурентов.
            Формулируй рекомендации коротко, в повелительном наклонении («Добавить сравнение тарифов»).
            Учитывай требования пользователя, если они есть. Пиши по-русски.
            """;

    static final String KEYWORDS = """
            Ты SEO-аналитик. Подбери ключевые запросы для статьи на русском языке.
            Основные запросы - короткие частотные формулировки темы, как их вводят в поиск.
            Первый основной запрос - главный, он пойдет в заголовок и введение.
            Дополнительные запросы - уточнения и смежные вопросы, которые встречаются в заголовках конкурентов.
            Запросы должны звучать естественно и вписываться в текст. Без кавычек, операторов и повторов.
            """;

    static final String OUTLINE = """
            Ты опытный редактор. Составь структуру SEO-статьи.
            Заголовок H1 содержит главный запрос и звучит естественно, без кликбейта.
            Разделы H2 раскрывают интент последовательно: от сути вопроса к практическим выводам.
            Подразделы H3 добавляй только там, где раздел действительно распадается на части.
            Учти структуры конкурентов, но не копируй их: закрой пробелы из рекомендаций.
            Если пользователь дал предварительный план, сохрани его логику и пункты, дополнив недостающим.
            Не включай отдельный раздел «Введение»: введение идет без заголовка.
            Обычно 5-8 разделов H2. Заголовки конкретные и разные по форме, без шаблонов вроде
            «Что такое X: полное руководство». Объем статьи оцени по объему материалов конкурентов.
            """;
}
